"""
Системний промпт: інструкція для моделі + уся база знань.

Логіка: модель НЕ знає нічого про бізнес. Усе, що вона може сказати,
ми кладемо сюди. Тому промпт = правила поведінки + факти з YAML бізнесу.

Правила, спільні для всіх бізнесів (мова, «лише з бази», не обіцяти дій, стиль),
живуть тут, у коді. Те, що залежить від бізнесу (роль, особливі правила, приклади),
береться з розділу `prompt:` у YAML — так другий бізнес не потребує правок коду.

Чому весь YAML, а не "знайти потрібний шматок" (RAG):
файл маленький (кілька тисяч токенів), модель бачить усе одразу і не пропустить
важливе через неточний пошук. RAG потрібен, коли документів сотні сторінок.
"""
from datetime import datetime

import yaml

from bot import hours, knowledge
from bot.knowledge import KB, SAFETY, facts

# Як назвати пояс у промпті. Пояс береться з YAML (schedule.timezone); раніше «час Києва»
# був зашитий у код. Для Києва текст той самий — промпт барбершопу не змінюється.
TZ_NAMES = {"Europe/Kyiv": "час Києва"}

DAYS_FULL_UA = ["понеділок", "вівторок", "середа", "четвер", "п'ятниця", "субота", "неділя"]

# YAML → текст один раз при старті. allow_unicode — щоб кирилиця не стала Б...
KNOWLEDGE_TEXT = yaml.safe_dump(facts(), allow_unicode=True, sort_keys=False)

# {плейсхолдери} заповнюються з розділу prompt: у YAML бізнесу.
RULES_TEMPLATE = """Ти — {role}. Відповідаєш клієнтам на питання.

МОВА: відповідай ТІЄЮ Ж мовою, якою написане останнє повідомлення клієнта.
Клієнт пише англійською — уся відповідь англійською: дані з бази перекладай, назви
послуг теж, без українських слів.
Будь-яка інша мова — відповідай українською.

ГОЛОВНЕ ПРАВИЛО: використовуй ТІЛЬКИ інформацію з розділу «БАЗА ЗНАНЬ» нижче.
- Ніколи не називай ціни, час, імена чи умови, яких там немає.
{data_rules}

ТИ НЕ ВИКОНУЄШ ДІЙ. Ти не можеш записати, перенести, скасувати, передати чи
перезвонити. Тому в полі answer НІКОЛИ не пиши «передам», «запишу», «уточню»,
«адміністратор зв'яжеться». Про передачу людині клієнту повідомить система.

Постав needs_human = true і відповідну reason, якщо:
{reasons}
В усіх інших випадках: needs_human = false, reason = none.

Що писати в answer, коли needs_human = true:
- якщо частину відповіді знаєш з бази — дай її (напр. ціну при записі);
- якщо інформації немає — чесно скажи, що в тебе немає цієї інформації;
- нічого не обіцяй.

Стиль:
- На питання «так чи ні» починай відповідь з «Так» або «Ні», потім коротко поясни.
- Коротко: 1–4 речення, без води. Дружньо, на «ви».
- Без Markdown-розмітки (*, #, **): Telegram покаже ці символи як є.
- Не вітайся в кожній відповіді — лише якщо клієнт привітався першим.

Питання не про {topic} (загальні знання, погода, політика, математика тощо):
НЕ відповідай на них навіть коротко — лише скажи, що допомагаєш тільки з
питаннями про {topic} (needs_human = false).{extra}"""

# Лише з safety.sensitive у YAML: тоді в схемі моделі є причина sensitive. {describe} — з YAML.
SENSITIVE_REASON = """- sensitive — делікатна тема: {describe}. Так само, якщо це написано з помилками,
  іншою мовою чи описово. В answer — коротко і співчутливо; ціну — лише якщо про неї прямо питають;"""

GENERIC_REASONS = """- booking — клієнт ПРОСИТЬ виконати дію: записати, перенести чи скасувати
  ЙОГО запис, або питає про вільний час (ти не бачиш розклад записів).
  Питання ПРО ПРАВИЛА («чи можна скасувати за годину?», «чи треба передоплата?»)
  — це НЕ booking: відповідай з бази, needs_human = false;
- human_request — клієнт просить адміністратора / живу людину;
- complaint — скарга, конфлікт, клієнт незадоволений;
- no_info — відповіді на питання немає в базі знань ({no_info_examples})."""


def build_rules() -> str:
    """Правила для моделі: загальні + специфічні для бізнесу з розділу prompt: у YAML."""
    p = KB.get("prompt") or {}
    reasons = GENERIC_REASONS.format(
        no_info_examples=p.get("no_info_examples", "послуги, яких немає в списку, тощо"))
    sensitive = SAFETY.get("sensitive") or {}
    if sensitive.get("describe"):
        reasons = SENSITIVE_REASON.format(describe=str(sensitive["describe"]).strip()) + "\n" + reasons
    if p.get("extra_reasons"):  # особливі причини (напр. невідкладний стан) — першими
        reasons = p["extra_reasons"].rstrip("\n") + "\n" + reasons
    extra = p.get("extra", "").rstrip("\n")
    return RULES_TEMPLATE.format(
        role=p.get("role", "помічник бізнесу в Telegram"),
        topic=p.get("topic", "бізнес"),
        data_rules=p.get("data_rules", "").rstrip("\n"),
        reasons=reasons,
        extra=f"\n\n{extra}" if extra else "",
    )


RULES = build_rules()


def open_status(now: datetime) -> str:
    """Чи відкрито зараз — пораховано кодом за графіком (лише якщо є ui.after_hours).

    Модель погано рахує дні тижня й години («сьогодні неділя, а відкриваються в понеділок о 10»),
    тому готову відповідь даємо їй рядком. Без графіка — порожньо, і промпт не змінюється.
    """
    schedule = knowledge.SCHEDULE
    if schedule is None:
        return ""
    prefix = "ЧИ ВІДКРИТО ЗАРАЗ (пораховано системою за графіком — спирайся саме на це)"
    if hours.is_open(schedule, now):
        closes = schedule.hours_on(now.date())[1]
        return f"\n{prefix}: відкрито, сьогодні до {closes:%H:%M}."
    opens = hours.describe_opening(now, hours.next_opening(schedule, now))
    return (f"\n{prefix}: зачинено, відкриється {opens}. Не пиши, що можна прийти "
            "чи що хтось відповість або візьме слухавку зараз.")


def build_system_prompt() -> str:
    """Збирає промпт заново на кожен запит — бо змінюється поточний час.

    Без часу модель не відповість на "ви зараз відкриті?" чи "а завтра працюєте?".
    Час — з knowledge.now(): тест-набір підставляє його для сценаріїв «у неділю».
    """
    tz = KB["schedule"]["timezone"]
    now = knowledge.now()
    now_text = f"{now:%Y-%m-%d %H:%M}, {DAYS_FULL_UA[now.weekday()]}"
    return (
        f"{RULES}\n\n"
        f"ЗАРАЗ: {now_text} ({TZ_NAMES.get(tz, f'часовий пояс {tz}')}).{open_status(now)}\n\n"
        f"=== БАЗА ЗНАНЬ ===\n{KNOWLEDGE_TEXT}"
    )
